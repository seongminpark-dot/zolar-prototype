function renderTimetable() {
  const grid = document.getElementById("timetableGrid")
  const summary = document.getElementById("scheduleSummary")
  const heatmap = document.getElementById("heatmap")

  if (!grid || !summary || !heatmap) return

  const days = ["Mon", "Tue", "Wed", "Thu", "Fri"]
  const times = ["9 AM", "10 AM", "11 AM", "12 PM", "1 PM", "2 PM", "3 PM", "4 PM", "5 PM", "6 PM", "7 PM", "8 PM"]

  grid.classList.add("hourly")

  let html = `<div class="time"></div>`
  days.forEach(day => {
    html += `<div class="day">${day}</div>`
  })

  times.forEach(time => {
    html += `<div class="time">${time}</div>`

    days.forEach(day => {
      const blocks = plannedCourses
        .map(code => courses[code])
        .filter(course => {
          const off = getOffering(course)
          return off && off.days.includes(day) && getTimeSlot(off.start) === time
        })

      if (blocks.length > 0) {
        html += `<div class="slot">`
        blocks.forEach(block => {
          const off = getOffering(block)
          html += `
            <div class="block ${isRisk(off) ? "red" : "blue"} ${moved ? "moved" : ""}">
              <div>
                ${block.code}<br>
                ${off.start} to ${off.end}<br>
                ${block.location}
              </div>
              <button data-drop="${block.code}">${lang("Drop", "삭제")}</button>
            </div>
          `
        })
        html += `</div>`
      } else {
        html += `
          <div class="slot">
            <button data-add-empty="${day}-${time}">${lang("Add", "추가")}</button>
          </div>
        `
      }
    })
  })

  grid.innerHTML = html

  if (plannedCourses.length === 0) {
    summary.innerHTML = `<p>${lang("No courses added yet. Return to Course Search and add a course to the plan.", "아직 추가된 과목이 없습니다. 과목 검색으로 돌아가 과목을 계획에 추가하세요.")}</p>`
    heatmap.innerHTML = ["low", "low", "low", "low", "low"].map(level => `<span class="${level}"></span>`).join("")
    return
  }

  summary.innerHTML = plannedCourses.map(code => {
    const course = courses[code]
    const off = getOffering(course)
    return `<p><strong>${course.code}</strong> · ${off.days} · ${off.start} to ${off.end} · ${course.location}</p>`
  }).join("")

  const hasRisk = plannedCourses.some(code => isRisk(getOffering(courses[code])))
  const heavyCount = plannedCourses.filter(code => workloadScore(getOffering(courses[code]).dna.workload) >= 4).length

  if (hasRisk && heavyCount >= 2) {
    heatmap.innerHTML = ["high", "mid", "high", "mid", "low"].map(level => `<span class="${level}"></span>`).join("")
  } else if (hasRisk) {
    heatmap.innerHTML = ["mid", "high", "mid", "mid", "low"].map(level => `<span class="${level}"></span>`).join("")
  } else {
    heatmap.innerHTML = ["low", "mid", "mid", "low", "low"].map(level => `<span class="${level}"></span>`).join("")
  }
}

function getTimeSlot(start) {
  if (!start) return "9 AM"
  if (start.includes("9:")) return "9 AM"
  if (start.includes("10:")) return "10 AM"
  if (start.includes("11:")) return "11 AM"
  if (start.includes("12:")) return "12 PM"
  if (start.includes("1:")) return "1 PM"
  if (start.includes("2:")) return "2 PM"
  if (start.includes("3:")) return "3 PM"
  if (start.includes("4:")) return "4 PM"
  if (start.includes("5:")) return "5 PM"
  if (start.includes("6:")) return "6 PM"
  if (start.includes("7:")) return "7 PM"
  if (start.includes("8:")) return "8 PM"
  return "9 AM"
}

