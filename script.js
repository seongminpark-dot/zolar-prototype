document.addEventListener("click", event => {
  const go = event.target.closest("[data-go]")
  if (go) {
    showPage(go.dataset.go)
    return
  }

  const select = event.target.closest("[data-select]")
  if (select) {
    selectedCourseId = select.dataset.select
    renderSearch()
    return
  }

  const roadmapCourse = event.target.closest("[data-roadmap-course]")
  if (roadmapCourse) {
    const code = roadmapCourse.dataset.roadmapCourse
    if (courses[code]) {
      selectedCourseId = code
      renderPathway()
    }
    return
  }

  const action = event.target.closest("[data-action]")

  if (action && action.dataset.action === "addCourse" && selectedCourseId) {
    if (!plannedCourses.includes(selectedCourseId)) plannedCourses.push(selectedCourseId)
    renderCourseDetail()
    return
  }

  if (action && action.dataset.action === "sendAdvisorEmail") {
    const status = document.getElementById("advisorSendStatus")
    if (status) {
      status.innerHTML = `<div class="sent-box">${lang("Email draft sent to the recommended office for review.", "이메일 초안이 권장 부서 검토용으로 전송되었습니다.")}</div>`
    }
    return
  }

  const drop = event.target.closest("[data-drop]")
  if (drop) {
    plannedCourses = plannedCourses.filter(code => code !== drop.dataset.drop)
    renderTimetable()
    return
  }

  const addEmpty = event.target.closest("[data-add-empty]")
  if (addEmpty) {
    if (selectedCourseId && !plannedCourses.includes(selectedCourseId)) {
      plannedCourses.push(selectedCourseId)
      renderTimetable()
    } else {
      showPage("search")
    }
    return
  }

  const suggestion = event.target.closest("[data-chat-suggestion]")
  if (suggestion) {
    sendChatMessage(suggestion.dataset.chatSuggestion)
  }
})

