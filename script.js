function renderSearch() {
  const {
    resultsEl,
    detailEl,
    inputEl,
    termEl,
    deptEl,
    levelEl,
    dayEl,
    riskEl,
    sortEl
  } = getSearchElements()

  if (!resultsEl || !detailEl) return

  const query = inputEl ? inputEl.value.trim().toLowerCase() : ""
  const term = termEl ? termEl.value : selectedTerm
  const dept = deptEl ? deptEl.value : "All"
  const level = levelEl ? levelEl.value : "All"
  const day = dayEl ? dayEl.value : "Any"
  const risk = riskEl ? riskEl.value : "All"
  const sort = sortEl ? sortEl.value : "relevance"

  selectedTerm = term

  let results = Object.values(courses).filter(course => {
    const offering = getOffering(course, term)
    const text = `${course.code} ${course.title} ${course.dept} ${course.level} ${course.location}`.toLowerCase()
    const upperQuery = query.toUpperCase()

    const matchQuery =
      !query ||
      text.includes(query) ||
      course.code.toLowerCase().startsWith(query) ||
      course.dept.toLowerCase() === query ||
      (upperQuery.length <= 3 && course.code.startsWith(upperQuery))

    const matchDept = dept === "All" || course.dept === dept
    const matchLevel = level === "All" || course.level === level
    const matchDay = day === "Any" || offering.days.includes(day)
    const matchRisk = risk === "All" || (risk === "Risk" && isRisk(offering)) || (risk === "Safe" && !isRisk(offering))

    return matchQuery && matchDept && matchLevel && matchDay && matchRisk
  })

  let fallbackMessage = ""

  if (results.length === 0) {
    results = Object.values(courses).filter(course => {
      const offering = getOffering(course, term)
      return dept === "All" || course.dept === dept || !offering
    })

    fallbackMessage = lang(
      "No exact match was found. Showing supported prototype courses instead.",
      "정확히 일치하는 과목이 없어 이 프로토타입에서 지원하는 과목 목록을 보여줍니다."
    )
  }

  if (sort === "rating") results.sort((a, b) => getOffering(b, term).evaluation.rating - getOffering(a, term).evaluation.rating)
  if (sort === "workload") results.sort((a, b) => workloadScore(getOffering(b, term).dna.workload) - workloadScore(getOffering(a, term).dna.workload))
  if (sort === "relevance") results.sort((a, b) => a.code.localeCompare(b.code))

  if (!selectedCourseId || !results.find(course => course.code === selectedCourseId)) {
    selectedCourseId = results.length > 0 ? results[0].code : null
  }

  resultsEl.innerHTML = `
    <div class="result-header">
      <div>
        <h3>${t("searchResultsTitle")}</h3>
        <p>${query ? lang("Filtered by your search.", "검색어에 따라 필터링되었습니다.") : t("emptySearchText")}</p>
        ${fallbackMessage ? `<p class="warning-note">${fallbackMessage}</p>` : ""}
      </div>
      <select id="quickDepartmentSelect">
        <option value="All">${lang("All", "전체")}</option>
        <option value="BIO">BIO</option>
        <option value="EST">EST</option>
        <option value="MAT">MAT</option>
        <option value="CHE">CHE</option>
        <option value="AMS">AMS</option>
        <option value="PSY">PSY</option>
        <option value="BUS">BUS</option>
      </select>
    </div>
    ${results.map(course => {
      const offering = getOffering(course, term)
      return `
        <div class="result-card ${selectedCourseId === course.code ? "active" : ""}" data-select="${course.code}">
          <h4>${course.code}</h4>
          <p>${course.title}</p>
          <p>${term} · ${offering.section} · ${offering.days} · ${offering.start} to ${offering.end}</p>
          <span class="badge ${isRisk(offering) ? "warning" : "safe"}">${translateStatus(offering.status)}</span>
          <p>${offering.evaluation.enrolled} ${lang("enrolled", "수강 인원")} · ${offering.evaluation.responses} ${lang("responses", "응답")} · ${offering.evaluation.rating} / 5</p>
        </div>
      `
    }).join("")}
  `

  const quickDepartmentSelect = document.getElementById("quickDepartmentSelect")
  if (quickDepartmentSelect) {
    quickDepartmentSelect.value = dept
    quickDepartmentSelect.addEventListener("change", event => {
      const deptEl = document.getElementById("departmentFilter")
      if (deptEl) deptEl.value = event.target.value
      renderSearch()
    })
  }

  renderCourseDetail()
}

function workloadScore(value) {
  if (!value) return 1
  if (value.includes("Very")) return 5
  if (value.includes("Intensive")) return 5
  if (value.includes("High")) return 4
  if (value.includes("Moderate High")) return 3
  if (value.includes("Moderate")) return 2
  return 1
}

